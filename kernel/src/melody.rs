// ─── Player ──────────────────────────────────────────────────────────
pub fn play<F: FnMut(u32)>(mut beep: F) {
    // wholenote = (60000 * 4) / tempo, giống bản Arduino
    let wholenote: u64 = (60_000u64 * 4) / TEMPO as u64;
    let mut count = 0u32;

    for (&freq, &sig) in MAIN_MELODY.iter().zip(MAIN_NOTES.iter()) {
        let base = wholenote / sig.unsigned_abs() as u64;
        let dur = if sig > 0 { base } else { (base * 3) / 2 };
        let play_ms = dur * 9 / 10;

        if freq == REST {
            beep(0);
            time::sleep_ms(dur);
        } else {
            beep(freq);
            time::sleep_ms(play_ms);
            beep(0);
            time::sleep_ms(dur - play_ms);
        }
        count += 1;
    }

    beep(0);
    crate::kprintln!("♪ played {} notes", count);
}